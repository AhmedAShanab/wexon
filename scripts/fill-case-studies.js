const CLIENTS = ['وكالة داخلية', 'عميل خاص', 'شركة ناشئة', 'علامة محلية', 'مجموعة تجارية'];
const DUR = { LOGO: '٣ أسابيع', 'SOCIAL MEDIA': 'شهري مستمر', PACKAGING: '٥ أسابيع', CAMPAIGN: '٦ أسابيع', BRANDING: '٦ أسابيع', 'VISUAL IDENTITY': '٥ أسابيع', FILM: '٨ أسابيع', MOTION: '٤ أسابيع', AD: '٥ أسابيع', REEL: 'أسبوعان' };

let filled = 0;
['images', 'videos'].forEach((listKey) => {
  (data.works[listKey] || []).forEach((w, i) => {
    if (!w.slug && SLUGS[w.id]) w.slug = SLUGS[w.id];
    if (w.caseStudy && Array.isArray(w.caseStudy.phases) && w.caseStudy.phases.length) return; // keep hand-written ones
    const tpl = T[w.tag] || T[listKey === 'videos' ? 'FILM' : 'BRANDING'];
    const n = nameOf(w.title);
    const c = tpl(n);
    if (!w.client) w.client = CLIENTS[i % CLIENTS.length];
    if (!w.year) w.year = '2026';
    if (!w.duration) w.duration = DUR[w.tag] || '٤ أسابيع';
    if (!w.detail) w.detail = c.intro.slice(0, 80) + '…';
    w.caseStudy = {
      intro: c.intro,
      objective: c.objective,
      services: c.services,
      tools: c.tools,
      ...(listKey === 'images' && c.palette ? { palette: c.palette } : {}),
      phases: c.phases.map(([title, body], j) => ({ title, body, media: seedOf(w.id, 'p' + (j + 1)) + '/1100/700' })),
      gallery: [1, 2, 3, 4, 5].map((g) => seedOf(w.id, 'g' + g) + (g % 2 ? '/900/1100' : '/1100/750')),
      outcome: c.outcome,
      quote: c.quote,
      quoteAuthor: 'فريق ' + n,
    };
    filled++;
  });
});

fs.writeFileSync(FILE, JSON.stringify(data, null, 2) + '\n', 'utf8');
